/// Which backend this build talks to.
///
/// Chosen by the Android build flavor (`--flavor staging` / `--flavor
/// production`), read here through Flutter's [appFlavor]. Keeping the Dart
/// choice tied to the native flavor means a staging APK can never end up
/// initialising Firebase against production by mistake — the native
/// google-services.json and these options always come from the same flavor.
enum AppEnvironment {
  production,
  staging;

  static AppEnvironment get current => appFlavor == 'staging'
      ? AppEnvironment.staging
      : AppEnvironment.production;

  bool get isStaging => this == AppEnvironment.staging;

  /// Firebase options for this environment on the current platform.
  ///
  /// Staging is Android-only for now; other platforms fall back to the
  /// production options generated by `flutterfire configure`.
  FirebaseOptions get firebaseOptions {
    if (isStaging &&
        !kIsWeb &&
        defaultTargetPlatform == TargetPlatform.android) {
      return _stagingAndroid;
    }
    return DefaultFirebaseOptions.currentPlatform;
  }

  /// From android/app/src/staging/google-services.json (project
  /// dilivvafast-staging, package com.dilivvafast.app.staging). Firebase
  /// client API keys are identifiers, not secrets — access is governed by
  /// the security rules — so they live in source like the production ones.
  static const _stagingAndroid = FirebaseOptions(
    apiKey: 'AIzaSyAkoOb0gul_5MskaYdYcLjcWTbbRuq0trE',
    appId: '1:54402955686:android:eb8098262392b19875b767',
    messagingSenderId: '54402955686',
    projectId: 'dilivvafast-staging',
    storageBucket: 'dilivvafast-staging.firebasestorage.app',
  );
}
